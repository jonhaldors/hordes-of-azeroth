#!/usr/bin/env python3
"""Generate the HoA protocol writer/decoder from shared/protocol/messages.yaml."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "shared" / "protocol" / "messages.yaml"
CONTENT_HASH = ROOT / "shared" / "content" / "content.hash"
CONTENT_MANIFEST = ROOT / "shared" / "content" / "content.manifest.json"
CPP_TARGET = ROOT / "server" / "src" / "game" / "Bonk" / "HoaProtocol.h"
RUST_TARGET = ROOT / "client" / "crates" / "hoa" / "src" / "protocol_generated.rs"

CPP_TYPES = {
    "u8": "uint8",
    "u16": "uint16",
    "u32": "uint32",
    "u64": "uint64",
    "i32": "int32",
    "f32": "float",
    "bool": "bool",
    "string": "std::string",
}
RUST_TYPES = {
    "u8": "u8",
    "u16": "u16",
    "u32": "u32",
    "u64": "u64",
    "i32": "i32",
    "f32": "f32",
    "bool": "bool",
    "string": "String",
}
RUST_READERS = {
    "u8": ("read_u8", "body[0]", "&body[1..]"),
    "u16": ("read_u16", None, None),
    "u32": ("read_u32", None, None),
    "u64": ("read_u64", None, None),
    "i32": ("read_i32", None, None),
    "f32": ("read_f32", None, None),
    "bool": ("read_bool", None, None),
    "string": ("read_string", None, None),
}


def load() -> dict:
    data = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or not isinstance(data.get("messages"), list):
        raise SystemExit("messages.yaml: expected a version and a message list")
    version = data.get("version")
    if not isinstance(version, int) or version < 1:
        raise SystemExit("messages.yaml: version must be a positive integer")
    seen_names: set[str] = set()
    seen_ids: set[int] = set()
    for message in data["messages"]:
        name = message.get("name")
        if not isinstance(name, str) or not name or name in seen_names:
            raise SystemExit(f"messages.yaml: bad or duplicate message name {name!r}")
        seen_names.add(name)
        message_id = message.get("id")
        if not isinstance(message_id, int) or not 1 <= message_id <= 0xFFFF or message_id in seen_ids:
            raise SystemExit(f"messages.yaml: bad or duplicate id for {name}")
        seen_ids.add(message_id)
        if message.get("direction") not in ("server_to_client", "client_to_server"):
            raise SystemExit(f"messages.yaml: {name} needs a direction")
        fields = message.get("fields")
        if not isinstance(fields, list):
            raise SystemExit(f"messages.yaml: {name} needs a field list")
        for field in fields:
            if not isinstance(field.get("name"), str) or field.get("type") not in CPP_TYPES:
                raise SystemExit(f"messages.yaml: {name} has a bad field")
    return data


def upper(name: str) -> str:
    return name.upper()


def camel(name: str) -> str:
    head, *tail = name.split("_")
    return head + "".join(part[:1].upper() + part[1:] for part in tail)


def rust_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def compile_cpp(schema: dict) -> bytes:
    lines = [
        "#pragma once",
        "",
        "// Generated by tools/protocol/gen.py from shared/protocol/messages.yaml.",
        "// Do not edit by hand.",
        "",
        '#include "WorldPacket.h"',
        "",
        "#include <string>",
        "",
        f"#define HOA_PROTOCOL_VERSION {schema['version']}",
    ]
    for message in schema["messages"]:
        lines.append(f"#define HOA_MSG_{upper(message['name'])} 0x{message['id']:04X}")
    lines.append("")
    lines += [
        "inline void HoAWriteString(WorldPacket& packet, std::string const& value)",
        "{",
        "    packet << uint16(value.size());",
        "    packet.append(reinterpret_cast<uint8 const*>(value.data()), value.size());",
        "}",
        "",
    ]
    for message in schema["messages"]:
        params = ", ".join(
            f"{CPP_TYPES[field['type']]} const& {camel(field['name'])}"
            if field["type"] != "string"
            else f"std::string const& {camel(field['name'])}"
            for field in message["fields"]
        )
        args = f", {params}" if params else ""
        lines += [
            f"inline void HoAWrite{camel(message['name'])[:1].upper()}{camel(message['name'])[1:]}"
            f"(WorldPacket& packet{args})",
            "{",
            f"    packet << uint16(HOA_MSG_{upper(message['name'])});",
        ]
        for field in message["fields"]:
            name = camel(field["name"])
            if field["type"] == "string":
                lines.append(f"    HoAWriteString(packet, {name});")
            else:
                lines.append(f"    packet << {CPP_TYPES[field['type']]}({name});")
        lines += ["}", ""]
    return "\n".join(lines).encode("utf-8")


def compile_rust(
    schema: dict,
    content_hash: str,
    sections: list[tuple[str, str]] | None = None,
) -> bytes:
    used: set[str] = set()
    for message in schema["messages"]:
        used.update(field["type"] for field in message["fields"])
    lines = [
        "// Generated by tools/protocol/gen.py from shared/protocol/messages.yaml.",
        "// Do not edit by hand.",
        "",
        f"pub const PROTOCOL_VERSION: u16 = {schema['version']};",
        f"pub const CONTENT_HASH: &str = {rust_string(content_hash)};",
        "",
    ]
    if sections:
        entries = ", ".join(
            f"({rust_string(name)}, {rust_string(hash_value)})"
            for name, hash_value in sections
        )
        lines.append(f"pub const CONTENT_SECTIONS: &[(&str, &str)] = &[{entries}];")
        lines.append("")
    for message in schema["messages"]:
        lines.append(f"pub const MSG_{upper(message['name'])}: u16 = 0x{message['id']:04X};")
    lines.append("")
    for message in schema["messages"]:
        struct = camel(message["name"])[:1].upper() + camel(message["name"])[1:]
        lines.append(f"pub struct {struct} {{")
        for field in message["fields"]:
            lines.append(f"    pub {field['name']}: {RUST_TYPES[field['type']]},")
        lines += ["}", ""]
    lines.append("pub enum HoaMessage {")
    for message in schema["messages"]:
        struct = camel(message["name"])[:1].upper() + camel(message["name"])[1:]
        lines.append(f"    {struct}({struct}),")
    lines += ["}", ""]

    lines.append("pub fn decode(id: u16, body: &[u8]) -> Option<HoaMessage> {")
    lines.append("    match id {")
    for message in schema["messages"]:
        struct = camel(message["name"])[:1].upper() + camel(message["name"])[1:]
        lines.append(
            f"        MSG_{upper(message['name'])} => decode_{message['name']}(body).map(HoaMessage::{struct}),"
        )
    lines += ["        _ => None,", "    }", "}", ""]

    for message in schema["messages"]:
        struct = camel(message["name"])[:1].upper() + camel(message["name"])[1:]
        lines.append(f"fn decode_{message['name']}(body: &[u8]) -> Option<{struct}> {{")
        if message["fields"]:
            lines.append("    let mut body = body;")
        for field in message["fields"]:
            lines.append(
                f"    let {field['name']} = {RUST_READERS[field['type']][0]}(&mut body)?;"
            )
        lines += ["    if !body.is_empty() {", "        return None;", "    }"]
        lines.append(f"    Some({struct} {{")
        for field in message["fields"]:
            lines.append(f"        {field['name']},")
        lines += ["    })", "}", ""]

    if "u8" in used:
        lines += [
            "fn read_u8(body: &mut &[u8]) -> Option<u8> {",
            "    let value = *body.first()?;",
            "    *body = &body[1..];",
            "    Some(value)",
            "}",
            "",
        ]
    for width in (16, 32, 64):
        kind = f"u{width}"
        if kind in used:
            lines += [
                f"fn read_{kind}(body: &mut &[u8]) -> Option<{kind}> {{",
                f"    let bytes: [u8; {width // 8}] = body.get(..{width // 8})?.try_into().ok()?;",
                "    *body = &body["
                f"{width // 8}..];",
                f"    Some({kind}::from_le_bytes(bytes))",
                "}",
                "",
            ]
    if "i32" in used:
        lines += [
            "fn read_i32(body: &mut &[u8]) -> Option<i32> {",
            "    let bytes: [u8; 4] = body.get(..4)?.try_into().ok()?;",
            "    *body = &body[4..];",
            "    Some(i32::from_le_bytes(bytes))",
            "}",
            "",
        ]
    if "f32" in used:
        lines += [
            "fn read_f32(body: &mut &[u8]) -> Option<f32> {",
            "    let bytes: [u8; 4] = body.get(..4)?.try_into().ok()?;",
            "    *body = &body[4..];",
            "    Some(f32::from_le_bytes(bytes))",
            "}",
            "",
        ]
    if "bool" in used:
        lines += [
            "fn read_bool(body: &mut &[u8]) -> Option<bool> {",
            "    read_u8(body).map(|value| value != 0)",
            "}",
            "",
        ]
    if "string" in used:
        lines += [
            "fn read_string(body: &mut &[u8]) -> Option<String> {",
            "    let len = usize::from(read_u16(body)?);",
            "    let text = body.get(..len)?;",
            "    *body = &body[len..];",
            "    String::from_utf8(text.to_vec()).ok()",
            "}",
            "",
        ]
    return "\n".join(lines).encode("utf-8")


def outputs(
    content_hash: str, sections: list[tuple[str, str]] | None = None
) -> list[tuple[str, Path, bytes]]:
    schema = load()
    return [
        ("protocol cpp", CPP_TARGET, compile_cpp(schema)),
        ("protocol rust", RUST_TARGET, compile_rust(schema, content_hash, sections)),
    ]


def read_content_hash() -> str:
    if not CONTENT_HASH.exists():
        raise SystemExit("shared/content/content.hash is missing; run tools/content/compile.py")
    return CONTENT_HASH.read_text(encoding="ascii").strip()


def read_content_sections() -> list[tuple[str, str]]:
    if not CONTENT_MANIFEST.exists():
        return []
    manifest = json.loads(CONTENT_MANIFEST.read_text(encoding="utf-8"))
    return sorted(
        (name, section["hash"])
        for name, section in (manifest.get("sections") or {}).items()
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = outputs(read_content_hash(), read_content_sections())
    if args.check:
        stale = [name for name, target, data in generated
                 if (target.read_bytes().replace(b"\r\n", b"\n") if target.exists() else b"") != data]
        if stale:
            print("generated protocol is out of date: " + ", ".join(stale))
            print("run tools/content/compile.py")
            return 1
        print("protocol: generated files are up to date")
        return 0
    for name, target, data in generated:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        print(f"wrote {target.relative_to(ROOT)} ({len(data)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
