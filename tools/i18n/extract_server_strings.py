"""Extract the server's BonkString table into the shared i18n catalogue.

One-time importer and refresh tool: it reads the current C++ `BonkString` table
and the zhCN export. Once `shared/i18n` is the source, edit `messages/server.yaml`
and run `gen_server_strings.py`; re-running this extractor overwrites manual
catalogue changes.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "shared" / "i18n" / "messages" / "server.yaml"

ENUM_RE = re.compile(r"BONK_STRING_([A-Z0-9_]+)\s*=\s*(\d+)")
TEXT_RE = re.compile(r'\{\s*BONK_STRING_([A-Z0-9_]+),\s*"((?:[^"\\]|\\.)*)"\s*\}')
PLACEHOLDER_RE = re.compile(r"\{(\d+)\}")


def unescape_cpp(text: str) -> str:
    return (
        text.replace("\\\\", "\\")
        .replace('\\"', '"')
        .replace("\\n", "\n")
        .replace("\\t", "\t")
        .replace("\\r", "\r")
    )


def placeholders(text: str) -> list[int]:
    return sorted({int(value) for value in PLACEHOLDER_RE.findall(text)})


def main() -> int:
    header = (ROOT / "server/src/game/Bonk/BonkStrings.h").read_text(encoding="utf-8")
    source = (ROOT / "server/src/game/Bonk/BonkStrings.cpp").read_text(encoding="utf-8")
    export = json.loads((ROOT / "localization/zhCN/server.json").read_text(encoding="utf-8"))

    ids = {name: int(value) for name, value in ENUM_RE.findall(header)}
    texts = {name: unescape_cpp(text) for name, text in TEXT_RE.findall(source)}
    translations = {
        item["id"]: item.get("translation", "")
        for item in export.get("strings", [])
        if item.get("translation")
    }

    missing_text = sorted(set(ids) - set(texts))
    missing_enum = sorted(set(texts) - set(ids))
    if missing_text or missing_enum:
        raise SystemExit(
            f"BonkStrings mismatch: enum without text={missing_text}, text without enum={missing_enum}"
        )

    entries = []
    for name in sorted(ids, key=lambda key: ids[key]):
        english = texts[name]
        entry = {
            "id": "hoa.msg." + name.lower(),
            "legacy_server_id": ids[name],
            "enUS": english,
        }
        translation = translations.get(ids[name], "")
        if translation:
            entry["zhCN"] = translation
        placeholders_found = placeholders(english)
        if placeholders_found:
            entry["placeholders"] = placeholders_found
        entries.append(entry)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    body = yaml.safe_dump(entries, allow_unicode=True, sort_keys=False, width=4096)
    header_comment = (
        "# Generated by tools/i18n/extract_server_strings.py from\n"
        "# server/src/game/Bonk/BonkStrings.{h,cpp} and localization/zhCN/server.json.\n"
        "# Do not hand-edit; re-run the extractor instead.\n"
    )
    OUT.write_text(header_comment + body, encoding="utf-8")

    translated = sum(1 for entry in entries if entry.get("zhCN"))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(entries)} messages, {translated} with zhCN")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
