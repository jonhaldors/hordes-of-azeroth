#!/usr/bin/env python3
"""Compile shared/content/cards/cards.yaml into SQL for the world database."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "protocol"))

import yaml

from gen import outputs as protocol_outputs
from tables import compile_tables
from spells import spell_outputs

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "shared" / "content" / "cards" / "cards.yaml"
TARGET = ROOT / "server" / "sql" / "content" / "bonk_card.sql"
HASH_TARGET = ROOT / "shared" / "content" / "content.hash"
MANIFEST_TARGET = ROOT / "shared" / "content" / "content.manifest.json"
HASH_SQL_TARGET = ROOT / "server" / "sql" / "content" / "hoa_content.sql"
HASH_HEADER_TARGET = ROOT / "server" / "src" / "game" / "Bonk" / "BonkContentHash.h"

SECTIONS = {
    "cards": [SOURCE],
    "spells": [ROOT / "shared" / "content" / "spells" / "spells.yaml"],
    "tables": sorted((ROOT / "shared" / "content" / "tables").glob("*.yaml")),
}


def digest_of(sources: list[Path]) -> str:
    digest = hashlib.sha256()
    for source in sources:
        digest.update(source.relative_to(ROOT).as_posix().encode("utf-8"))
        digest.update(b"\x00")
        digest.update(source.read_bytes().replace(b"\r\n", b"\n"))
    return "sha256:" + digest.hexdigest()


def content_hash() -> str:
    return digest_of([SOURCE, *SECTIONS["tables"], *SECTIONS["spells"]])


def section_hashes() -> dict[str, str]:
    return {name: digest_of(files) for name, files in SECTIONS.items()}


def compile_manifest(hash_value: str) -> bytes:
    manifest = {
        "schema": 1,
        "hash": hash_value,
        "sections": {
            name: {
                "hash": digest_of(files),
                "files": [source.relative_to(ROOT).as_posix() for source in files],
            }
            for name, files in sorted(SECTIONS.items())
        },
    }
    return (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8")


def compile_hash_sql(hash_value: str) -> bytes:
    return "\n".join([
        "-- Generated by tools/content/compile.py from the content sources.",
        "-- Do not edit by hand.",
        "",
        "CREATE TABLE IF NOT EXISTS `hoa_content` (",
        "  `id` tinyint(3) unsigned NOT NULL,",
        "  `hash` varchar(80) NOT NULL,",
        "  PRIMARY KEY (`id`)",
        ") ENGINE=MyISAM DEFAULT CHARSET=utf8;",
        "",
        "REPLACE INTO `hoa_content` (`id`, `hash`) VALUES (1, " + quote(hash_value) + ");",
        "",
        "CREATE TABLE IF NOT EXISTS `hoa_content_section` (",
        "  `name` varchar(32) NOT NULL,",
        "  `hash` varchar(80) NOT NULL,",
        "  PRIMARY KEY (`name`)",
        ") ENGINE=MyISAM DEFAULT CHARSET=utf8;",
        "",
        "DELETE FROM `hoa_content_section`;",
        "INSERT INTO `hoa_content_section` (`name`, `hash`) VALUES",
        ",\n".join("  (" + quote(name) + ", " + quote(section_hashes()[name]) + ")"
                   for name in sorted(SECTIONS)) + ";",
        "",
    ]).encode("utf-8")


def compile_hash_header(hash_value: str) -> bytes:
    sections = section_hashes()
    rows = ",\n".join(
        f'    {{"{name}", "{sections[name]}"}}' for name in sorted(sections)
    )
    text = ";".join(f"{name}={sections[name]}" for name in sorted(sections))
    return "\n".join([
        "#pragma once",
        "",
        "// Generated by tools/content/compile.py from the content sources.",
        "// Do not edit by hand.",
        "",
        f'#define HOA_CONTENT_HASH "{hash_value}"',
        f'#define HOA_CONTENT_SECTIONS_TEXT "{text}"',
        "",
        "struct HoaContentSection",
        "{",
        "    char const* name;",
        "    char const* hash;",
        "};",
        "",
        "static constexpr HoaContentSection HOA_CONTENT_SECTIONS[] =",        "{",
        rows,
        "};",
        "",
    ]).encode("utf-8")


def quote(text: str) -> str:
    return "'" + str(text).replace("\\", "\\\\").replace("'", "''") + "'"


def number(value: float) -> str:
    return format(float(value), ".10g")


def compile_cards() -> bytes:
    data = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    if not isinstance(data, list):
        raise SystemExit("cards.yaml: top level must be a list")
    seen: set[int] = set()
    rows = []
    translations = []
    for entry in data:
        card_id = entry.get("id")
        if not isinstance(card_id, int) or card_id in seen:
            raise SystemExit(f"cards.yaml: bad or duplicate id {card_id!r}")
        seen.add(card_id)
        for field in ("name", "icon", "description", "name_zhCN", "description_zhCN"):
            if not isinstance(entry.get(field), str) or not entry[field].strip():
                raise SystemExit(f"cards.yaml: card {card_id} missing {field}")
        stats = entry.get("stats") or []
        if len(stats) > 2:
            raise SystemExit(f"cards.yaml: card {card_id} has more than two stats")
        stat_values = [(255, 0.0), (255, 0.0)]
        for index, stat in enumerate(stats):
            stat_values[index] = (int(stat["effect"]), float(stat["value"]))
        values = [float(value) for value in entry.get("values") or [0, 0, 0]]
        if len(values) != 3:
            raise SystemExit(f"cards.yaml: card {card_id} needs three values")
        rows.append(
            "("
            + ", ".join(
                [
                    str(card_id),
                    quote(entry["name"]),
                    quote(entry["icon"]),
                    quote(entry["description"]),
                    str(int(entry["rarity"])),
                    str(stat_values[0][0]),
                    number(stat_values[0][1]),
                    str(stat_values[1][0]),
                    number(stat_values[1][1]),
                    str(int(entry["effect"])),
                    number(values[0]),
                    number(values[1]),
                    number(values[2]),
                    str(int(entry.get("cooldown_ms", 0))),
                    str(int(entry.get("max_copies", 0))),
                    "1" if entry.get("in_chests") else "0",
                ]
            )
            + ")"
        )
        translations.append(
            "(" + ", ".join([str(card_id), quote("zhCN"), quote(entry["name_zhCN"]), quote(entry["description_zhCN"])]) + ")"
        )

    sql = [
        "-- Generated by tools/content/compile.py from shared/content/cards/cards.yaml.",
        "-- Do not edit by hand.",
        "",
        "DELETE FROM `bonk_card`;",
        "INSERT INTO `bonk_card`",
        "  (`id`, `name`, `icon`, `description`, `rarity`, `stat1`, `stat1_value`, `stat2`, `stat2_value`,",
        "   `effect`, `value1`, `value2`, `value3`, `cooldown_ms`, `max_copies`, `in_chests`)",
        "VALUES",
        ",\n".join("  " + row for row in rows) + ";",
        "",
        "DELETE FROM `bonk_card_locale` WHERE `locale` = 'zhCN';",
        "INSERT INTO `bonk_card_locale` (`id`, `locale`, `name`, `description`)",
        "VALUES",
        ",\n".join("  " + row for row in translations) + ";",
        "",
    ]
    return "\n".join(sql).encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if the generated SQL differs")
    args = parser.parse_args()
    hash_value = content_hash()
    sections = sorted(section_hashes().items())
    generated = [
        ("cards", TARGET, compile_cards()),
        *spell_outputs(),
        *protocol_outputs(hash_value, sections),
        ("content hash sql", HASH_SQL_TARGET, compile_hash_sql(hash_value)),
        ("content hash header", HASH_HEADER_TARGET, compile_hash_header(hash_value)),
        ("content manifest", MANIFEST_TARGET, compile_manifest(hash_value)),
    ]
    for path, table_sql in compile_tables():
        generated.append((path.stem, ROOT / "server" / "sql" / "content" / f"{path.stem}.sql", table_sql))

    if args.check:
        stale = []
        for name, target, sql in generated:
            current = target.read_bytes().replace(b"\r\n", b"\n") if target.exists() else b""
            if current != sql:
                stale.append(name)
        if stale:
            print("generated content is out of date: " + ", ".join(stale))
            print("run tools/content/compile.py")
            return 1
        expected_hash = hash_value + "\n"
        current_hash = HASH_TARGET.read_text(encoding="ascii") if HASH_TARGET.exists() else ""
        if current_hash != expected_hash:
            print("content.hash is out of date; run tools/content/compile.py")
            return 1
        print(f"content: {len(generated)} generated files are up to date")
        return 0

    for name, target, sql in generated:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(sql)
        print(f"wrote {target.relative_to(ROOT)} ({len(sql)} bytes)")

    HASH_TARGET.write_text(hash_value + "\n", encoding="ascii")
    print(f"wrote {HASH_TARGET.relative_to(ROOT)} ({hash_value})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
